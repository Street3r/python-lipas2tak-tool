"""Publish a public build to a git branch (e.g. GitHub Pages).

The public build is made from the saved raw data with:
- the project's own icon set (a custom set such as pilot icons is never published),
- the public base URL (written into KML network links, QR codes and pages),
- no per-group KMZ files (keeps the file count reasonable).

The target branch is replaced by a single new commit on every publish, so it
only holds the latest version. Nothing is pushed if no file changed apart
from files that carry the run time (index.json, index.html, CHANGELOG.md).
"""
from __future__ import annotations

import json
import logging
import os
import shutil
import subprocess
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

from . import attribution, pipeline
from .config import Settings

log = logging.getLogger(__name__)

# Files whose content changes on every run; a change in these alone is not published
VOLATILE = {"index.json", "index.html", "status.json", "CHANGELOG.md"}
CHANGELOG_KEEP = 52

BRANCH_README = """# {repo_name} – generated data

This branch is **generated** and replaced on every update; it only holds the latest version.
Do not edit it by hand.

- Start page: [index.html](index.html) · QR codes: [share/en](share/en/index.html), [share/fi](share/fi/index.html)
- Changes: [CHANGELOG.md](CHANGELOG.md)
- Licence: [ODbL 1.0]({licence_url}) – {attribution}

Generated by [python-lipas2tak-tool](https://github.com/Street3r/python-lipas2tak-tool).
"""


def public_settings(settings: Settings, workdir: Path, base_url: str) -> Settings:
    raw = json.loads(json.dumps(settings.raw))  # deep copy
    paths = raw.setdefault("paths", {})
    paths["output"] = str(workdir / "output")
    paths["cache"] = str(workdir / "cache")
    paths["icons"] = paths.get("icons_fallback") or "icons/retkeily"   # never a custom set
    raw["public_base_url"] = base_url.rstrip("/")
    outs = raw.setdefault("outputs", {})
    outs["kmz_per_group"] = False
    outs["network_link_per_group"] = False
    return Settings(raw=raw, kinds=settings.kinds, groups=settings.groups, root=settings.root,
                    area_names=settings.area_names)


def _git(repo: Path, *args: str, check: bool = True, capture: bool = False, env: Optional[dict] = None) -> str:
    res = subprocess.run(["git", *args], cwd=repo, check=check, text=True,
                         stdout=subprocess.PIPE if capture else None,
                         env={**os.environ, **(env or {})})
    return (res.stdout or "").strip() if capture else ""


def _prepare_repo(repo: Path, url: str, branch: str) -> None:
    if not (repo / ".git").exists():
        repo.mkdir(parents=True, exist_ok=True)
        _git(repo, "init", "-q")
        _git(repo, "remote", "add", "origin", url)
    else:
        _git(repo, "remote", "set-url", "origin", url)
    exists = subprocess.run(["git", "ls-remote", "--exit-code", "--heads", "origin", branch], cwd=repo,
                            stdout=subprocess.DEVNULL).returncode == 0
    if exists:
        _git(repo, "fetch", "-q", "--depth", "1", "origin", branch)
        _git(repo, "checkout", "-q", "-B", branch, "FETCH_HEAD")
        _git(repo, "reset", "-q", "--hard", "FETCH_HEAD")
    else:
        _git(repo, "checkout", "-q", "--orphan", branch)
    _git(repo, "clean", "-qfdx")


def _sync_tree(src: Path, repo: Path) -> None:
    for p in repo.iterdir():
        if p.name == ".git":
            continue
        shutil.rmtree(p) if p.is_dir() else p.unlink()
    for p in src.rglob("*"):
        if p.is_file():
            dst = repo / p.relative_to(src)
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(p, dst)


def _changelog(old: str, now: datetime, changes: dict, n_features: int) -> str:
    lines = [f"## {now.strftime('%Y-%m-%d')}", "", f"{n_features} features."]
    for key, v in sorted(changes.items()):
        if key.endswith("/en"):
            continue  # same changes as /fi
        area = key.rsplit("/", 1)[0]
        lines.append(f"- {area}: +{len(v['added'])} new, -{len(v['removed'])} removed, "
                     f"~{len(v['modified'])} changed")
    if not changes:
        lines.append("- format or layout changes only")
    entry = "\n".join(lines) + "\n"
    old_entries = [e for e in old.split("\n## ")[1:]] if old.startswith("# ") else []
    kept = ["## " + e.rstrip() + "\n" for e in old_entries[: CHANGELOG_KEEP - 1]]
    return "# Changelog\n\nLatest updates of the generated data.\n\n" + "\n".join([entry, *kept])


def publish(settings: Settings, raw_dir: Path, workdir: Path, repo_url: str, branch: str, base_url: str,
            repo_name: str = "finland-outdoor-tak-data", dry_run: bool = False,
            now: Optional[datetime] = None, source_status: Optional[Path] = None) -> str:
    """Build the public version and push it if anything changed. Returns a status string."""
    now = now or datetime.now(timezone.utc)
    workdir.mkdir(parents=True, exist_ok=True)
    pub = public_settings(settings, workdir, base_url)
    raw = pipeline.RawData.load(raw_dir)
    # Next scheduled check comes from the generator's own status file
    next_check = None
    if source_status and source_status.exists():
        nc = json.loads(source_status.read_text(encoding="utf-8")).get("next_check")
        next_check = datetime.fromisoformat(nc) if nc else None
    res = pipeline.run(pub, raw, now=now, next_check=next_check)
    out = pub.path("output")

    repo = workdir / "repo"
    _prepare_repo(repo, repo_url, branch)
    old_changelog = (repo / "CHANGELOG.md").read_text(encoding="utf-8") if (repo / "CHANGELOG.md").exists() else ""
    _sync_tree(out, repo)
    (repo / ".nojekyll").write_text("", encoding="utf-8")
    (repo / "README.md").write_text(BRANCH_README.format(
        repo_name=repo_name, licence_url=attribution.LICENSE_URL,
        attribution="; ".join(attribution.ATTRIBUTION)), encoding="utf-8")
    (repo / "ATTRIBUTION.txt").write_text(attribution.notice_text(), encoding="utf-8")
    if old_changelog:  # keep the changelog; a new entry is added below only for real changes
        (repo / "CHANGELOG.md").write_text(old_changelog, encoding="utf-8")

    _git(repo, "add", "-A")
    changed = [n for n in _git(repo, "diff", "--cached", "--name-only", check=False, capture=True).splitlines() if n]
    head_exists = subprocess.run(["git", "rev-parse", "-q", "--verify", "HEAD"], cwd=repo,
                                 stdout=subprocess.DEVNULL).returncode == 0
    if not head_exists:
        changed = _git(repo, "ls-files", capture=True).splitlines()
    real = [n for n in changed if n not in VOLATILE]
    if not changed:
        log.info("Publish: nothing to do")
        return "unchanged"
    if real:
        (repo / "CHANGELOG.md").write_text(_changelog(old_changelog, now, res["changes"], res["features"]),
                                           encoding="utf-8")
        _git(repo, "add", "-A")
        msg = f"Data update {now.strftime('%Y-%m-%d')} ({len(real)} files changed)"
    else:
        # Only the check time changed: publish it so the pages show the data was verified.
        # The branch keeps a single commit, so this does not grow the repository.
        msg = f"Data checked {now.strftime('%Y-%m-%d')}, no changes"
    if dry_run:
        log.info("Publish (dry run): %s, not pushed", msg)
        return f"dry-run: {len(real)} files"
    ident = {
        "GIT_AUTHOR_NAME": os.environ.get("PUBLISH_GIT_NAME", "lipas2tak publisher"),
        "GIT_AUTHOR_EMAIL": os.environ.get("PUBLISH_GIT_EMAIL", "lipas2tak@users.noreply.github.com"),
    }
    ident["GIT_COMMITTER_NAME"], ident["GIT_COMMITTER_EMAIL"] = ident["GIT_AUTHOR_NAME"], ident["GIT_AUTHOR_EMAIL"]
    tree = _git(repo, "write-tree", capture=True)
    commit = _git(repo, "commit-tree", tree, "-m", msg, capture=True, env=ident)
    _git(repo, "push", "-q", "--force", "origin", f"{commit}:refs/heads/{branch}")
    _git(repo, "reset", "-q", "--hard", commit)
    log.info("Published %s to %s: %s", commit[:8], branch, msg)
    return f"published: {len(real)} files" if real else "checked: no changes"


def watch(settings: Settings, source_index: Path, interval_s: float, **kw) -> None:
    """Publish whenever the generator has produced a new output (index.json changes)."""
    marker = Path(kw["workdir"]) / "last_source.txt"
    while True:
        try:
            if source_index.exists():
                generated = json.loads(source_index.read_text(encoding="utf-8")).get("generated", "")
                last = marker.read_text(encoding="utf-8").strip() if marker.exists() else ""
                if generated and generated != last:
                    log.info("New generator output (%s), publishing", generated)
                    publish(settings, source_status=source_index.parent / "status.json", **kw)
                    marker.write_text(generated, encoding="utf-8")
            else:
                log.info("Waiting for generator output: %s", source_index)
        except Exception:  # keep the container running; retry on the next round
            log.exception("Publish failed")
        time.sleep(interval_s)
